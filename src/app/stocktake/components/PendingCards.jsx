import { fmtDateTime, fmtInt, listName, plural } from './format'

// props: cycles (open_cycles of the store), busy (string or null), onOpen(cycleId), onDownload(cycleId)
export default function PendingCards({ cycles, busy, onOpen, onDownload }) {
  const list = Array.isArray(cycles) ? cycles : []
  return (
    <section className="stk-section" aria-labelledby="stk-pending-title">
      <h2 id="stk-pending-title" className="stk-h2">
        Pending lists
      </h2>
      {list.length === 0 ? (
        <p className="stk-note">No list pending today.</p>
      ) : (
        <ul className="stk-cards">
          {list.map((c) => {
            const open = Number(c.flagged_open) || 0
            return (
              <li key={c.cycle_id} className="stk-card">
                <h3 className="stk-card-title">{listName(c)}</h3>
                <p className="stk-caption">
                  Generated by {c.generated_by} on {fmtDateTime(c.generated_at)}
                </p>
                <p className="stk-progress-text">
                  {fmtInt(c.captured)} of {fmtInt(c.line_count)} captured
                </p>
                {open > 0 ? (
                  <p className="stk-caption">
                    {fmtInt(open)} {plural(open, 'line differs', 'lines differ')} from the system and
                    {plural(open, ' needs', ' need')} a decision.
                  </p>
                ) : null}
                <div className="stk-actions">
                  <button type="button" className="stk-btn stk-btn-primary" onClick={() => onOpen && onOpen(c.cycle_id)}>
                    Open
                  </button>
                  <button
                    type="button"
                    className="stk-btn stk-btn-secondary"
                    disabled={Boolean(busy)}
                    onClick={() => onDownload && onDownload(c.cycle_id)}
                  >
                    {busy === 'download:' + c.cycle_id ? 'Working' : 'Download sheets'}
                  </button>
                </div>
              </li>
            )
          })}
        </ul>
      )}
    </section>
  )
}
